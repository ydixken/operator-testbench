package e2e

import (
	"os"
	"strings"
	"testing"

	"github.com/ydixken/operator-testbench/internal/testbench"
	"github.com/ydixken/operator-testbench/operators"
)

const chartScenarios = "../../charts/operator-testbench/files/scenarios.yaml"

// The chart creates the scenario namespaces from files/scenarios.yaml, and the
// engine refuses a provided namespace that is missing. A scenario added to a
// pack without regenerating the file would fail in every cluster-mode run, so
// the file must equal what the embedded packs say. UPDATE_CHART=1 (task
// chart:generate) writes it instead.
func TestChartScenariosAreCurrent(t *testing.T) {
	packs, err := testbench.ListPacks(operators.FS)
	if err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	b.WriteString("# Generated by task chart:generate from the embedded packs; do not edit.\n")
	for _, name := range packs {
		pack, err := testbench.LoadPack(operators.FS, name, "", goStepNames())
		if err != nil {
			t.Fatal(err)
		}
		b.WriteString(name + ":\n")
		for _, sc := range pack.Scenarios {
			b.WriteString("  - " + sc.Name + "\n")
		}
	}
	if os.Getenv("UPDATE_CHART") == "1" {
		if err := os.WriteFile(chartScenarios, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got := read(t, chartScenarios); got != b.String() {
		t.Errorf("%s is stale; run task chart:generate\n got:\n%s\nwant:\n%s", chartScenarios, got, b.String())
	}
}
